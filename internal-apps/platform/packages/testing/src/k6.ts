export interface K6Request {
  method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";
  path: string;
  body?: unknown;
}

export interface K6Scenario {
  name: string;
  baseUrl: string;
  vus: number;
  /** e.g. "30s", "5m" */
  duration: string;
  requests: K6Request[];
  thresholds?: Record<string, string>;
}

/**
 * Build a k6 script (JS source) for a queue scenario — consumed by
 * per-app perf scripts (apps/<app>/scripts/perf) and template-smoke.
 */
export function k6ScenarioBuilder(s: K6Scenario): string {
  const calls = s.requests
    .map((r) => {
      const url = `\`\${BASE_URL}${r.path}\``;
      if (r.method === "GET" || r.method === "DELETE") {
        return `  http.${r.method.toLowerCase()}(${url});`;
      }
      return `  http.${r.method.toLowerCase()}(${url}, JSON.stringify(${JSON.stringify(r.body ?? {})}), { headers: { "Content-Type": "application/json" } });`;
    })
    .join("\n");
  const thresholds = Object.entries(s.thresholds ?? {})
    .map(([k, v]) => `      "${k}": ["${v}"],`)
    .join("\n");
  return `// generated by @company/testing k6ScenarioBuilder — do not hand-edit
import http from "k6/http";

const BASE_URL = "${s.baseUrl}";

export const options = {
  vus: ${s.vus},
  duration: "${s.duration}",
  thresholds: {
${thresholds}
  },
};

export default function () {
${calls}
}
`;
}
